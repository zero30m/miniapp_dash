function fromEntries(entries) {
    return entries.reduce(function (acc, entry) {
        acc[entry[0]] = entry[1];
        return acc;
    }, {});
}

function mapCards(entries) {
    return fromEntries(entries.map(function (entry) {
        return [entry[0], {
            description: entry[1]
        }];
    }));
}

